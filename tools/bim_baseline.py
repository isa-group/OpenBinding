"""Write the semantic BIM baseline goldens of the platform, computed with ``bim_core``.

The extraction of BIM into its own repository changes ``compilerDigest``, ``irDigest`` and the bundled
versions, so those cannot prove that the meaning survived.  The baseline records what must not move
instead: the semantic digest of every package, the result of the canonical evaluator on its bindings,
Engine mode compatibility, the diagnostics of negative cases, the re-evaluation vectors and the protocol
and schema digests.

The language is not in this repository any more, so neither is the computation: it lives in
``bim-toolchain/tools/baseline_core.py`` (``bim_core`` only), and this entry point only gives it the
platform's corpus, Engine manifests and golden directory.  ``tests/test_bim_baseline.py`` runs the same
functions and compares them with the goldens, which are not regenerated by a normal change; see
``docs/qa/BIM_BASELINE.md``.  Whatever is expected to change with the toolchain lives under a
``toolchain`` key, which :func:`comparable` removes.

Write the goldens (from the repository root)::

    uv run --project openbinding-gateway --locked python tools/bim_baseline.py
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE_TOOL = ROOT / "bim-toolchain" / "tools" / "baseline_core.py"

GOLDEN_DIR = ROOT / "openbinding-gateway" / "tests" / "golden" / "bim_baseline"
GOLDEN_FILES = ("corpus.json", "negatives.json", "compat.json", "vectors.json", "protocol.json")
MANIFEST_DIR = ROOT / "schemas" / "bim" / "v1" / "manifests"


def _load_core():
    spec = importlib.util.spec_from_file_location("baseline_core", CORE_TOOL)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("baseline_core", module)
    spec.loader.exec_module(module)
    return module


core = _load_core()
dump = core.dump
comparable = core.comparable
stable = core.stable


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the semantic BIM baseline goldens")
    parser.add_argument("--output", type=Path, default=GOLDEN_DIR)
    parser.add_argument("--expected", type=int, default=82)
    parser.add_argument("--jobs", type=int, default=min(4, os.cpu_count() or 1))
    args = parser.parse_args(argv)

    directories = core.package_directories(ROOT)
    manifests = core.engine_manifests(MANIFEST_DIR)
    corpus, compat = core.build_corpus_and_compat(directories, ROOT, args.jobs, manifests)
    failures = {path: entry["error"] for path, entry in corpus["packages"].items() if entry["status"] != "compiled"}
    if len(directories) != args.expected:
        failures["corpus"] = f"expected {args.expected} packages, found {len(directories)}"
    if failures:
        for path, error in sorted(failures.items()):
            print(f"{path}: {error}", file=sys.stderr)
        return 1

    documents = {
        "corpus.json": corpus,
        "negatives.json": core.build_negatives(ROOT),
        "compat.json": compat,
        "vectors.json": core.build_vectors(ROOT),
        "protocol.json": core.build_protocol(manifests),
    }
    args.output.mkdir(parents=True, exist_ok=True)
    for name in GOLDEN_FILES:
        data = dump(documents[name])
        (args.output / name).write_bytes(data)
        print(f"{name}: {len(data)} bytes sha256={hashlib.sha256(data).hexdigest()}")
    print(f"BIM baseline: {len(directories)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
