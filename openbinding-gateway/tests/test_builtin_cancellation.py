@pytest.mark.parametrize("name", BUNDLED)
async def test_a_cancelled_job_sends_the_delete_to_the_engine_that_declares_it_and_to_no_other(
    name, db_session, owner, engine_http
):
    installed = registration(name)
    endpoint = installed["document"]["spec"]["endpoint"]
    job = await a_job(db_session, owner, service_url=endpoint)
    assert await leases.claim_job(db_session, job.id) is not None
    await db_session.commit()
    await execution.record_engine_job_id(db_session, job.id, "engine-job-X")
    await db_session.execute(update(Job).where(Job.id == job.id).values(state=JobState.CANCELLED))
    await db_session.commit()
    context = execution.attempt_cancel_context(
        execution.registration_cancellation(installed), engines.registration_transport(installed)
    )

    await execution.cancel_engine_attempt(db_session, job.id, 1, context)

    row = (await db_session.execute(select(JobEngineAttempt).where(JobEngineAttempt.job_id == job.id))).scalars().one()
    if name == "minizinc-csp":
        assert engine_http.deleted == [(f"engine-{name}", "/internal/v1/jobs/engine-job-X")]
        assert row.cancel_state == "sent"
    else:
        assert engine_http.requests == []
        assert row.cancel_state == "none"  # never claimed: the door is shut before any claim
