BUNDLED = ("minizinc-csp", "random-search", "many-heuristic", "evolutionary-heuristics")
JAVA = ("many-heuristic", "evolutionary-heuristics")
JOB_PATH = "/internal/v1/jobs/{id}"
ENDPOINTS = {name: f"http://engine-{name}:3000" for name in BUNDLED}


@pytest.fixture(autouse=True)
def default_deployment(monkeypatch):
    """No operator list, and a refusal logged by an earlier test is logged again."""
    monkeypatch.delenv(engines.BUILTIN_CANCELLATION_ENV, raising=False)
    monkeypatch.setattr(engines, "_REFUSED_CANCELLATION_NAMES", set())


def registration(name: str) -> dict:
    installed = engines.installed_builtin_registration(engines.manifest(name), ENDPOINTS[name])
    assert installed is not None
    return installed


def capability(name: str):
    return execution.registration_cancellation(registration(name))


def spec_of(name: str) -> dict:
    return registration(name)["document"]["spec"]


# -- What the registration declares ----------------------------------------------------------------------


def test_minizinc_declares_per_attempt_cancellation_and_describes_the_delete_the_gateway_requires():
    spec = spec_of("minizinc-csp")

    assert spec["extensions"] == {"cancellation": {"supported": True, "idScope": "attempt"}}
    operation = spec["openapi"]["paths"][JOB_PATH]["delete"]
    assert {"200", "202", "404"} <= set(operation["responses"])
    assert "get" in spec["openapi"]["paths"][JOB_PATH]  # the protocol's own operation stays
    found = capability("minizinc-csp")
    assert found.declared and found.supported and found.per_attempt, found.reason


@pytest.mark.parametrize("name", [name for name in BUNDLED if name != "minizinc-csp"])
def test_the_other_bundled_engines_declare_nothing_by_default(name):
    spec = spec_of(name)

    assert "extensions" not in spec
    assert "delete" not in spec["openapi"]["paths"].get(JOB_PATH, {})
    found = capability(name)
    assert not found.declared and not found.supported


@pytest.mark.parametrize("name", [name for name in BUNDLED if name != "minizinc-csp"])
def test_an_engine_without_the_capability_keeps_the_registration_it_always_had(name):
    spec = spec_of(name)

    assert set(spec) == {"engine", "endpoint", "protocol", "mappings", "auth", "openapi"}
    assert spec["openapi"] == {
        **engines.protocol_document(),
        "x-bim-protocol": "bim-engine/v1",
        "x-bim-protocol-digest": engines.protocol_digest(),
    }


def test_the_protocol_document_is_not_changed_by_declaring_the_delete():
    before = engines.protocol_document()
    snapshot = repr(before)

    registration("minizinc-csp")

    assert repr(engines.protocol_document()) == snapshot
    assert "delete" not in before.get("paths", {}).get(JOB_PATH, {})


def test_the_declaration_is_a_valid_registration_document():
    for name in BUNDLED:
        assert engines.schema_diagnostics(registration(name)["document"], "EngineRegistration") == []
        assert engines.embedded_secret_paths(registration(name)["document"]) == []


def test_the_table_names_the_engine_by_its_manifest_and_only_minizinc_is_in_it():
    assert set(engines.BUILTIN_CANCELLATION) == {"minizinc-csp"}
    assert engines.builtin_cancellation_engines() == frozenset({"minizinc-csp"})
    assert engines.builtin_cancellation("minizinc-csp") == {"supported": True, "idScope": "attempt"}
    assert engines.builtin_cancellation("random-search") is None
    # a copy: a caller cannot change what the next registration declares
    engines.builtin_cancellation("minizinc-csp")["supported"] = False
    assert engines.builtin_cancellation("minizinc-csp")["supported"] is True


# -- Immutability and idempotence --------------------------------------------------------------------------


def test_installing_again_is_idempotent_and_the_version_is_the_digest_of_the_installation():
    first, second = registration("minizinc-csp"), registration("minizinc-csp")

    assert first is second
    assert first["version"].split("+builtin.", 1)[1] == engines.digest(first["document"]["spec"]).removeprefix("sha256-")
    assert engines.registration_reference(first) == engines.registration_reference(second)
    assert first["document"]["metadata"]["version"] == first["version"]


def test_declaring_the_capability_is_a_new_immutable_version(monkeypatch):
    declared = registration("minizinc-csp")
    monkeypatch.setattr(engines, "BUILTIN_CANCELLATION", {})

    undeclared = registration("minizinc-csp")

    assert "extensions" not in undeclared["document"]["spec"]
    assert undeclared["version"] != declared["version"] and undeclared["digest"] != declared["digest"]
    assert undeclared["version"].split("+builtin.")[0] == declared["version"].split("+builtin.")[0]
    # both stay installed side by side: a job that pinned one never meets the other under its name
    assert engines.BUILTIN_REGISTRATIONS[tuple(declared[f] for f in ("namespace", "name", "version", "digest"))] is declared


def test_a_pinned_reference_resolves_to_its_own_registration_only(monkeypatch):
    manifest = engines.manifest("minizinc-csp")
    declared = registration("minizinc-csp")
    reference = {field: declared[field] for field in ("namespace", "name", "version", "digest")}
    assert engines.installed_builtin_registration(manifest, ENDPOINTS["minizinc-csp"], reference) is declared

    monkeypatch.setattr(engines, "BUILTIN_CANCELLATION", {})

    # without the declaration the same reference no longer names the installation: the job fails closed
    assert engines.installed_builtin_registration(manifest, ENDPOINTS["minizinc-csp"], reference) is None


