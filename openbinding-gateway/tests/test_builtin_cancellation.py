"""The bundled engines' registration declares cancellation, and only for the engines that always implement it.

``jobs/remote_attempts.py`` and ``services/execution.py`` send a ``DELETE`` only when the registration declares
``spec.extensions.cancellation`` and its OpenAPI describes that operation. The registration of a bundled engine is
generated by ``services.engines.builtin_engine_registration``; these tests pin what it declares:

* ``minizinc-csp`` declares the capability (``idScope: attempt``) and describes the ``DELETE``;
* the other bundled engines declare nothing, and their registration is exactly what it was before;
* ``ENGINE_CANCELLATION_BUILTIN`` (validated, empty by default) adds bundled engines the operator runs with a
  ``DELETE`` (the Java engines in ``ENGINE_JOB_MODE=async``);
* the gateway's decision (``decide``) and the door every cancellation goes through send a ``DELETE`` to an engine
  that declares it and to no other; the rules R1-R5 are those of ``test_remote_cancel.py``, untouched.

Everything is local: SQLite and ``httpx.MockTransport``; no engine is contacted.
"""

