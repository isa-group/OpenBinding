@pytest.mark.parametrize("name", JAVA)
def test_a_java_engine_declares_cancellation_only_when_the_operator_names_it(name, monkeypatch):
    off = registration(name)
    assert not capability(name).supported

    monkeypatch.setenv(engines.BUILTIN_CANCELLATION_ENV, name)
    on = registration(name)

    assert on["document"]["spec"]["extensions"] == {"cancellation": {"supported": True, "idScope": "attempt"}}
    found = execution.registration_cancellation(on)
    assert found.supported and found.per_attempt, found.reason
    assert on["version"] != off["version"] and on["digest"] != off["digest"]
    others = [other for other in JAVA if other != name]
    assert all(not capability(other).supported for other in others)
    assert not capability("random-search").supported

    monkeypatch.delenv(engines.BUILTIN_CANCELLATION_ENV)
    assert registration(name) is off  # switching it off again is the registration of before, same object


def test_the_list_takes_several_names_with_blanks_and_keeps_minizinc(monkeypatch):
    monkeypatch.setenv(engines.BUILTIN_CANCELLATION_ENV, " many-heuristic , ,evolutionary-heuristics,")

    assert engines.builtin_cancellation_engines() == frozenset({"minizinc-csp", *JAVA})
    assert capability("many-heuristic").supported and capability("evolutionary-heuristics").supported
    assert capability("minizinc-csp").supported and not capability("random-search").supported


