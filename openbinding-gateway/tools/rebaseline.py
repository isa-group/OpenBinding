#!/usr/bin/env python3
"""Regenerate the single Alembic revision from the models (decision D1 of the F0b plan).

Nothing is in production, so the schema has no migration history: there is one
revision, the baseline, and a change to the models regenerates it instead of
stacking a migration on top. The baseline is generated, never edited by hand:

    python tools/rebaseline.py            # rewrite alembic/versions/<rev>_baseline.py
    python tools/rebaseline.py --check    # fail if it differs from the models (ignoring the rev id)

What it does:

1. autogenerates the whole schema against an empty SQLite database (Alembic's
   ``produce_migrations``, the engine of ``alembic revision --autogenerate``);
2. renders every partial-index ``WHERE`` with the dialect it is for (the
   autogenerated text compiles both with SQLite, and ``archived = 0`` is not a
   boolean test on PostgreSQL);
3. adds the ``use_alter`` foreign keys (``jobs.study_cell_id`` closes the
   ``jobs`` <-> ``study_cells`` cycle) with ``op.create_foreign_key`` after
   every table on PostgreSQL; SQLite keeps them inline, since it accepts a
   forward reference in ``CREATE TABLE`` and has no ``ADD CONSTRAINT``;
4. freezes the trigger DDL of ``db/triggers.py`` as literal per-dialect
   strings, so the migration never imports application code;
5. writes a real ``downgrade()``: the ``use_alter`` foreign keys, the tables in
   reverse order, then the PostgreSQL trigger functions.

Each regeneration takes a fresh random revision id, so a database built from an
older baseline fails loudly (``alembic/env.py`` prints the reset recipe)
instead of drifting silently. ``--check`` compares with the id masked.
"""

from __future__ import annotations

import argparse
import difflib
import os
import re
import secrets
import sys
import tempfile
from pathlib import Path

GATEWAY_ROOT = Path(__file__).resolve().parents[1]
VERSIONS = GATEWAY_ROOT / "alembic" / "versions"

sys.path.insert(0, str(GATEWAY_ROOT / "src"))

HEADER = '''"""The whole schema, in one revision.

Generated by ``tools/rebaseline.py`` from the models and ``db/triggers.py``; do
not edit it by hand. A schema change edits the models and regenerates this file
(``python tools/rebaseline.py``), which also changes the revision id: a database
built from an older baseline is then refused by ``alembic/env.py`` and has to
be rebuilt (README, "Reset the dev database").
"""
from typing import Sequence, Union

from alembic import op
import sqlalchemy as sa


revision: str = {revision!r}
down_revision: Union[str, None] = None
branch_labels: Union[str, Sequence[str], None] = None
depends_on: Union[str, Sequence[str], None] = None

'''


def _metadata():
    from openbinding_gateway.db import models  # noqa: F401  (registers every table and the triggers)
    from openbinding_gateway.db.base import Base

    return Base.metadata


def _autogenerate(metadata) -> tuple[str, str]:
    """The upgrade and downgrade bodies Alembic autogenerates against an empty SQLite database."""
    from alembic.autogenerate import produce_migrations, render_python_code
    from alembic.migration import MigrationContext
    from sqlalchemy import create_engine

    with tempfile.TemporaryDirectory() as scratch:
        engine = create_engine(f"sqlite:///{Path(scratch) / 'empty.db'}")
        try:
            with engine.connect() as connection:
                context = MigrationContext.configure(
                    connection, opts={"compare_type": True, "target_metadata": metadata}
                )
                script = produce_migrations(context, metadata)
                upgrade = render_python_code(script.upgrade_ops, migration_context=context)
                downgrade = render_python_code(script.downgrade_ops, migration_context=context)
        finally:
            engine.dispose()
    return _strip_markers(upgrade), _strip_markers(downgrade)


def _strip_markers(code: str) -> str:
    lines = [line for line in code.splitlines() if not line.strip().startswith("# ###")]
    return "\n".join(line.rstrip() for line in lines).strip("\n")


def _dialect_where_clauses(code: str, metadata) -> str:
    """Render each ``<dialect>_where`` of a partial index with its own dialect."""
    from sqlalchemy.dialects import postgresql, sqlite

    dialects = {"sqlite": sqlite.dialect(), "postgresql": postgresql.dialect()}
    for table in metadata.sorted_tables:
        for index in table.indexes:
            for name, dialect in dialects.items():
                where = index.dialect_options[name]["where"]
                if where is None:
                    continue
                as_sqlite = str(where.compile(dialect=dialects["sqlite"], compile_kwargs={"literal_binds": True}))
                own = str(where.compile(dialect=dialect, compile_kwargs={"literal_binds": True}))
                rendered = f"{name}_where=sa.text({as_sqlite!r})"
                wanted = f"{name}_where=sa.text({own!r})"
                lines = code.splitlines()
                for number, line in enumerate(lines):
                    if f"'{index.name}'" in line and rendered in line:
                        lines[number] = line.replace(rendered, wanted)
                code = "\n".join(lines)
                if wanted not in code:
                    raise SystemExit(f"rebaseline: cannot find the {name} WHERE of index {index.name}")
    return code


def _use_alter_foreign_keys(metadata) -> list:
    return sorted(
        (
            constraint
            for table in metadata.sorted_tables
            for constraint in table.foreign_key_constraints
            if constraint.use_alter
        ),
        key=lambda constraint: constraint.name,
    )


def _python_list(name: str, items: list[str]) -> str:
    body = "".join(f"    {item!r},\n" for item in items)
    return f"{name} = (\n{body})\n"


def build(revision: str) -> str:
    from openbinding_gateway.db.triggers import TRIGGERS, function_names, render

    metadata = _metadata()
    upgrade, downgrade = _autogenerate(metadata)
    upgrade = _dialect_where_clauses(upgrade, metadata)
    downgrade = _dialect_where_clauses(downgrade, metadata)

    late = _use_alter_foreign_keys(metadata)
    add_late = "".join(
        f"        op.create_foreign_key({fk.name!r}, {fk.parent.name!r}, {fk.referred_table.name!r}, "
        f"{[c.name for c in fk.columns]!r}, {[e.column.name for e in fk.elements]!r}"
        + (f", ondelete={fk.ondelete!r}" if fk.ondelete else "")
        + (f", onupdate={fk.onupdate!r}" if fk.onupdate else "")
        + ")\n"
        for fk in late
    )
    drop_late = "".join(
        f"        op.drop_constraint({fk.name!r}, {fk.parent.name!r}, type_='foreignkey')\n" for fk in late
    )

    parts = [HEADER.format(revision=revision)]
    parts.append("# Frozen from openbinding_gateway/db/triggers.py by tools/rebaseline.py.\n")
    parts.append(_python_list("SQLITE_TRIGGERS", render("sqlite", TRIGGERS)))
    parts.append(_python_list("POSTGRESQL_TRIGGERS", render("postgresql", TRIGGERS)))
    parts.append(_python_list("POSTGRESQL_TRIGGER_FUNCTIONS", function_names(TRIGGERS)))
    parts.append("\n\ndef upgrade() -> None:\n")
    parts.append("    dialect = op.get_bind().dialect.name\n")
    parts.append(upgrade + "\n")
    if late:
        parts.append("    # Foreign keys that close a cycle: inline on SQLite, added once both tables exist elsewhere.\n")
        parts.append("    if dialect != 'sqlite':\n" + add_late)
    parts.append("    for statement in {'sqlite': SQLITE_TRIGGERS, 'postgresql': POSTGRESQL_TRIGGERS}[dialect]:\n")
    parts.append("        op.execute(statement)\n")
    parts.append("\n\ndef downgrade() -> None:\n")
    parts.append("    dialect = op.get_bind().dialect.name\n")
    if late:
        parts.append("    if dialect != 'sqlite':\n" + drop_late)
    parts.append(downgrade + "\n")
    parts.append("    if dialect == 'postgresql':\n")
    parts.append("        for function in POSTGRESQL_TRIGGER_FUNCTIONS:\n")
    parts.append("            op.execute(f'DROP FUNCTION IF EXISTS {function}()')\n")
    return "".join(parts)


REVISION_LINE = re.compile(r"^revision: str = '([0-9a-f]{12})'$", re.MULTILINE)


def committed() -> list[Path]:
    return sorted(path for path in VERSIONS.glob("*.py"))


def masked(text: str) -> str:
    return REVISION_LINE.sub("revision: str = '<rev>'", text)


def check() -> int:
    files = committed()
    if len(files) != 1 or not files[0].name.endswith("_baseline.py"):
        print(f"rebaseline: expected exactly one *_baseline.py in {VERSIONS}, found {[f.name for f in files]}")
        return 1
    current = files[0].read_text(encoding="utf-8")
    match = REVISION_LINE.search(current)
    if match is None or not files[0].name.startswith(match.group(1)):
        print(f"rebaseline: {files[0].name} does not carry its own revision id")
        return 1
    fresh = build("0" * 12)
    if masked(current) == masked(fresh):
        print(f"rebaseline: {files[0].name} matches the models")
        return 0
    diff = difflib.unified_diff(
        masked(current).splitlines(keepends=True), masked(fresh).splitlines(keepends=True),
        f"committed/{files[0].name}", "regenerated",
    )
    sys.stdout.writelines(diff)
    print("\nrebaseline: the baseline is out of date; run python tools/rebaseline.py and commit the result")
    return 1


def write() -> Path:
    revision = secrets.token_hex(6)
    text = build(revision)
    for path in committed():
        path.unlink()
    target = VERSIONS / f"{revision}_baseline.py"
    target.write_text(text, encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed baseline differs from the models")
    arguments = parser.parse_args(argv)
    os.environ.setdefault("APP_ENV", "dev")
    if arguments.check:
        return check()
    print(f"rebaseline: wrote {write().relative_to(GATEWAY_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
