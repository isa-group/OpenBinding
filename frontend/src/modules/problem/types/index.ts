// What the problem module's screens pass each other: the organization a problem belongs to and the problem with its
// revisions.

import type { Problem, ProblemRevision } from '../api/problemsClient';
import type { ProblemOrigin } from '../../core/api/types';

/** The organization that owns a problem, as the screens name it. */
export interface ProblemOrg {
  slug: string;
  name: string;
}

/** A problem and its sealed revisions, newest first. */
export interface ProblemContent {
  item: Problem;
  revisions: Array<ProblemRevision & { origin?: ProblemOrigin }>;
}

/** What each origin of a revision is called on screen. SPHERE is recorded by the gateway already and filtered from F3. */
export const ORIGIN_LABELS: Readonly<Record<ProblemOrigin, string>> = {
  upload: 'Uploaded',
  editor: 'Problem editor',
  qacoforge: 'QACOForge',
  sphere: 'SPHERE',
};

/** Where a revision came from, as the header's origin line says it. */
export const ORIGIN_LINES: Readonly<Record<ProblemOrigin, string>> = {
  upload: 'Uploaded as a BIM package',
  editor: 'Written in the problem editor',
  qacoforge: 'Generated by QACOForge',
  sphere: 'Imported from SPHERE',
};
