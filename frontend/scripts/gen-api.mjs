// Writes src/modules/core/api/openapi.ts, the TypeScript types of the gateway API, from the committed snapshot docs/openapi.json.
//
//   pnpm gen:api            regenerate the file
//   pnpm gen:api --check    exit 1 when the committed file differs from what the snapshot generates
//
// The snapshot is the gateway's contract (openbinding-gateway/tools/dump_openapi.py keeps it current), so a gateway change that
// alters a view fails `--check` until the types are regenerated in the same commit.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const snapshot = new URL('../../docs/openapi.json', import.meta.url);
const target = new URL('../src/modules/core/api/openapi.ts', import.meta.url);

const HEADER = `// Generated by frontend/scripts/gen-api.mjs from docs/openapi.json. Do not edit by hand: run \`pnpm gen:api\`.
`;

const schema = JSON.parse(await readFile(snapshot, 'utf8'));
const generated = HEADER + astToString(await openapiTS(schema));

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = await readFile(target, 'utf8');
  } catch {
    // A missing file is a difference like any other.
  }
  if (current !== generated) {
    console.error(
      `${fileURLToPath(target)} is out of date with docs/openapi.json. Run \`pnpm gen:api\` and commit the result.`
    );
    process.exit(1);
  }
  console.log('src/modules/core/api/openapi.ts matches docs/openapi.json.');
} else {
  await writeFile(target, generated);
  console.log(`Wrote ${fileURLToPath(target)}.`);
}
