"""``golden/synthetic/corpus.json``: the golden that needs no OpenBinding corpus.

The 82-package corpus lives in OpenBinding; a repository exported from it has none, so what it compares with a golden is
the set of packages that live here: the five synthetic variants of ``synthetic_packages.py`` and
``fixtures/example-package``.  The golden holds, for each, what ``golden/bim_normalized`` holds for a corpus package (semantic
and section digests, evaluations, binding space), its compatibility with the four Engines and whether every form of it
(directory, raw ZIP in either order, canonical ZIP, two shuffles of its JSON members) compiles to the same IR.  It is
generated by ``tools/regen_normalized_metadata.py`` from the same function this test calls.
"""

from __future__ import annotations

import json

import pytest

import regen_normalized_metadata as regen
from core_support import engine_manifest_fixtures

REGENERATE = "run tools/regen_normalized_metadata.py --write"
PACKAGES = {
    "example-package",
    "synthetic/ordered",
    "synthetic/unordered-candidates",
    "synthetic/unordered-catalogs",
    "synthetic/unordered-constraint-sets",
    "synthetic/unordered-constraints",
}


@pytest.fixture(scope="module")
def golden() -> dict:
    assert regen.SYNTHETIC.is_file(), f"{regen.SYNTHETIC} does not exist: {REGENERATE}"
    return json.loads(regen.SYNTHETIC.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def fresh() -> dict:
    return regen.fresh_synthetic()


def test_the_golden_is_in_the_canonical_byte_form(baseline_tool, golden) -> None:
    assert baseline_tool.dump(golden) == regen.SYNTHETIC.read_bytes()
    assert golden["schema"] == "bim-baseline/synthetic/1"


def test_the_golden_is_what_the_toolchain_computes_for_these_packages(baseline_tool, golden, fresh) -> None:
    assert sorted(fresh["corpus"]["packages"]) == sorted(PACKAGES)
    assert baseline_tool.differences("synthetic corpus", fresh["corpus"], golden["corpus"]) == []
    assert baseline_tool.differences("synthetic compat", fresh["compat"], golden["compat"]) == []
    assert baseline_tool.differences("synthetic zip", fresh["zipEquivalence"], golden["zipEquivalence"]) == []
    assert baseline_tool.comparable(fresh) == baseline_tool.comparable(golden)


def test_its_toolchain_members_are_the_installed_ones(baseline_tool, golden, fresh) -> None:
    assert baseline_tool.dump(fresh) == regen.SYNTHETIC.read_bytes(), REGENERATE
    assert golden["toolchain"] == fresh["toolchain"]
    for path, entry in golden["corpus"]["packages"].items():
        assert entry["toolchain"] == fresh["corpus"]["packages"][path]["toolchain"], path


def test_every_package_compiles_and_is_evaluated(golden) -> None:
    corpus = golden["corpus"]
    assert golden["packageCount"] == corpus["packageCount"] == len(PACKAGES)
    assert set(corpus["packages"]) == PACKAGES
    for path, entry in corpus["packages"].items():
        assert entry["status"] == "compiled", path
        assert entry["semanticDigest"].startswith("sha256-"), path
        assert entry["evaluation"]["mode"] == "exhaustive", path
        assert entry["evaluation"]["count"] == int(entry["bindingSpace"]["cardinality"]) > 0, path


def test_every_form_of_every_package_is_the_package_compiled_from_its_directory(baseline_tool, golden) -> None:
    document = golden["zipEquivalence"]
    assert baseline_tool.zip_equivalence_failures(document) == {}
    assert set(document["packages"]) == PACKAGES and document["packageCount"] == len(PACKAGES)
    for path, entry in document["packages"].items():
        for form in baseline_tool.ZIP_FORMS:
            assert entry[form] == {"sameIr": True, "sameSemanticDigest": True}, (path, form)
        assert entry["packageDigestsEqual"], path


def test_the_compatibility_covers_the_four_engines_for_every_package(golden) -> None:
    compat = golden["compat"]
    engines = set(engine_manifest_fixtures())
    assert set(compat["engines"]) == engines and len(engines) == 4
    assert set(compat["packages"]) == PACKAGES
    for path, found in compat["packages"].items():
        assert set(found) == engines, path


def test_the_tool_agrees(capsys) -> None:
    assert regen.main(["--check", "--synthetic-only"]) == 0
    assert "0 problems" in capsys.readouterr().out
